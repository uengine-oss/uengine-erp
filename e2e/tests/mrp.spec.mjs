/** Types the way a person does, so every keystroke's own handlers run. */
async function type(input, text) {
  await input.click()
  await input.pressSequentially(text, { delay: 15 })
}
/** Over what is in the box already. */
async function retype(input, text) {
  await input.click()
  await input.press('ControlOrMeta+a')
  await input.pressSequentially(text, { delay: 15 })
}
/** Opens the list by clicking, types part of the name, and clicks the row that appears. */
async function choose(page, input, text) {
  await input.click()
  await input.pressSequentially(text, { delay: 15 })
  const option = page.locator('.combo-menu').getByRole('option', { name: new RegExp(text) }).first()
  await option.waitFor()
  await option.click()
  await expect(input).toHaveValue(new RegExp(text))
}
async function menu(page, module, screen) {
  await page.locator(`[data-module="${module}"]`).click()
  if (screen) await page.locator(`[data-screen="${screen}"]`).click()
}
async function openRow(page, text) {
  await rows(page).filter({ hasText: text }).first().click()
  await expect(page.getByTestId('meta-form')).toBeVisible()
}
const onHand = async (variant) => Number((await sql('select coalesce(sum(qty), 0) q from erp.quants where variant_id = $1', [variant])).rows[0].q)
const tick = (token) => rest('erp_bus_tick', { p_budget_ms: 3000 }, token)
async function settled(token, check, what) {
  await waitFor(async () => { await tick(token); return check() }, what, 120)
}

