test('속성의 값은 속성을 고른 뒤에 선택지로 나타난다', async ({ page }) => {
  test.skip(!installed, '기초데이터 모듈이 빌드에 없다')
  await connectAndLogin(page)
  await page.goto('/#/r/attribute/new')
  await fieldInput(page, 'name').fill('색상')
  const values = page.locator('[data-field="values"]')
  for (const name of ['빨강', '파랑']) {
    await values.getByTestId('line-add').click()
    await cell(values.locator('tbody tr[data-row]').last(), 'name').fill(name)
  }
  await page.getByTestId('save').click()
  await expect(page.getByTestId('form-title')).toHaveText('색상')

  await page.goto('/#/r/product/new')
  await fieldInput(page, 'name').fill('티셔츠')
  await pickRef(fieldInput(page, 'category_id'), '기본')
  await pickRef(fieldInput(page, 'uom_id'), '개')
  const attrs = page.locator('[data-field="attributes"]')
  await attrs.getByTestId('line-add').click()
  const row = attrs.locator('tbody tr[data-row]').first()
  await expect(row.locator('[data-col="value_ids"]')).toContainText('앞 칸을 먼저 고르세요')
  await pickRef(cell(row, 'attribute_id'), '색상')
  await row.locator('[data-col="value_ids"]').getByRole('button', { name: '빨강' }).click()
  await row.locator('[data-col="value_ids"]').getByRole('button', { name: '파랑' }).click()
  await shot(page, '57-product-attributes')
  await page.getByTestId('save').click()
  await expect(page.getByTestId('form-title')).toHaveText('티셔츠')
  await expect(page.locator('[data-field="variants"] tbody tr[data-row]')).toHaveCount(2)
  await shot(page, '58-product-variants')
})

