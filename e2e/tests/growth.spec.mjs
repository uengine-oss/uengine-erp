async function switchUser(page, user) {
  await page.getByTestId('logout').click()
  await login(page, user)
}

async function enableOnScreen(page, id, label) {
  await page.goto('/#/settings/modules')
  await card(page, id).getByTestId('module-enable').click()
  await expect(page.getByRole('dialog')).toContainText(`${label} 모듈 켜기`)
}

/** A quote and an order through the API, as another person's browser would. */
async function confirmedOrder(qty) {
  const o = await command(salesToken, 'sales_order', null, 'create', { partner_id: customer, lines: [{ variant_id: variantId, qty }] })
  await command(salesToken, 'sales_order', o.id, 'confirm')
  await deliver(admin)
  return o.id
}
const pickingOf = async (orderId) => (await sql(`select id, status, state from erp.records where type = 'picking' and not deleted and state ->> 'origin_id' = $1 order by created_at`, [orderId])).rows
const onHand = async () => Number((await sql(`select coalesce(sum(qty), 0) as q from erp.quants where variant_id = $1`, [variantId])).rows[0].q)

