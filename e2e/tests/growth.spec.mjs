test('S2. 적게 출고하면 남은 수량을 묻고, 재고가 모자라도 주문은 막히지 않는다', async ({ page }) => {
  const orderId = await confirmedOrder(10)
  await connectAndLogin(page, STOCK)
  await page.goto(`/#/r/picking/${(await pickingOf(orderId))[0].id}`)
  await cell(lines(page, 'moves').first(), 'done').fill('4')
  await page.getByTestId('tr-validate').click()
  await expect(page.getByRole('dialog')).toContainText('요구 수량보다 적게 처리합니다')
  await expect(page.getByRole('dialog').locator('textarea'), 'JSON 을 묻지 않는다').toHaveCount(0)
  await shot(page, '140-growth-s2-backorder')
  await page.getByRole('dialog').getByLabel('남은 수량').selectOption('true')
  await page.getByTestId('dlg-confirm').click()
  await expect(pipelineOn(page)).toHaveText('완료')
  await deliver(admin)
  const slips = await pickingOf(orderId)
  expect(slips.length, '나머지는 새 전표로').toBe(2)
  expect(Number(slips[1].state.moves[0].demand)).toBe(6)
  expect(slips[1].status).not.toBe('done')
  expect((await sql(`select state ->> 'delivery_status' as s from erp.records where id = $1`, [orderId])).rows[0].s).toBe('partial')

  const short = await confirmedOrder(100000)
  expect((await sql('select status from erp.records where id = $1', [short])).rows[0].status, '재고가 없어도 주문은 된다').toBe('sale')
  const [slip] = await pickingOf(short)
  await page.goto(`/#/r/picking/${slip.id}`)
  // Whatever is on the shelf is held for it; the slip waits for the rest.
  await expect(pipelineOn(page)).not.toHaveText('완료')
  expect(Number(slip.state.moves[0].reserved ?? 0)).toBeLessThan(100000)
  await shot(page, '141-growth-s2-short')
  await command(salesToken, 'sales_order', short, 'cancel')
  await deliver(admin)
  // What was reserved for it comes back, so later slips are not starved in this test.
  await page.goto('/#/inventory/stock')
  await expect(page.getByTestId('stock-table')).toBeVisible()
  await expectFitsWidth(page, '.page-head')
})

