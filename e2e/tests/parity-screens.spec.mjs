test('사람 속도로 주문 줄을 넣어도 제품의 단가와 세금이 채워지고, 고친 단가는 수량을 바꿔도 남는다', async ({ page }) => {
  await connectAndLogin(page)
  await page.goto('/#/r/sales_order/new')
  await pickRef(fieldInput(page, 'partner_id'), '가온마트')
  await human(page)
  await page.getByTestId('line-add').first().click()
  await human(page)
  await expect(page.getByTestId('preview-error')).toHaveCount(0)
  const row = lines(page).first()
  await pickRef(cell(row, 'variant_id'), '에어서큘레이터')
  await expect(cell(row, 'price_unit')).toHaveValue('89,000')
  await expect(row.locator('[data-col="tax_ids"] .tag')).toContainText('부가세')
  await expect(total(page, 'amount_total')).toHaveText('97,900')
  await human(page)

  await pickRef(cell(row, 'variant_id'), '제습기')
  await expect(cell(row, 'price_unit'), '제품을 바꾸면 단가도 따라온다').toHaveValue('150,000')
  await expect(cell(row, 'name')).toHaveValue('제습기')
  await human(page)

  await cell(row, 'price_unit').fill('120000')
  await human(page)
  await cell(row, 'qty').fill('3')
  await human(page)
  await expect(cell(row, 'price_unit'), '사람이 고친 단가는 남는다').toHaveValue('120,000')
  await expect(total(page, 'amount_untaxed')).toHaveText('360,000')
  await page.getByTestId('save').click()
  await expect(page).toHaveURL(/sales_order\/[0-9a-f-]{36}/)
  const saved = (await stateOf(idOf(page))).lines[0]
  expect([saved.price_unit, saved.qty, saved.price_manual, saved.cost]).toEqual([120000, 3, true, 90000])
  expect(saved.preview_echo, '미리 보기의 메모는 저장되지 않는다').toBeUndefined()

  await page.reload()
  await human(page)
  await expect(page.getByTestId('dirty-mark'), '열어 보기만 한 문서는 바뀐 것이 없다').toHaveCount(0)
  await expect(page.getByTestId('save')).toBeDisabled()
  await shot(page, '300-human-speed-order')
})

