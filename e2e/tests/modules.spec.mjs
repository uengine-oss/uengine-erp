test('쓰기는 한 곳에서만 나간다: 화면에 erp_command 호출이 없다', () => {
  const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]))
  const hits = walk(path.join(root, 'web', 'src'))
    .filter((f) => /\.(vue|ts)$/.test(f) && !f.includes('generated'))
    .filter((f) => /'erp_command'/.test(fs.readFileSync(f, 'utf8')))
    .map((f) => path.relative(root, f))
  expect(hits).toEqual(['web/src/lib/commands.ts'])
})
