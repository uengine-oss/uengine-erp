  for (const c of commands) expect(c.p_app_version, '모든 명령이 앱 버전을 싣는다').toMatch(/^\d+\.\d+\.\d+$/)
  expect(ticks).toBeGreaterThanOrEqual(2)
  expect(ticks, '명령 하나에 약 다섯 번까지만 재촉한다').toBeLessThanOrEqual(10)
